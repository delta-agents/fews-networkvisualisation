with tab3:
    st.header("Custom Health Checks")
    
    st.markdown("""
    Run custom SQL queries to analyze specific aspects of your FEWS configuration.
    Use these queries to identify issues or potential improvements in your configuration.
    """)
    
    # Predefined queries
    st.subheader("Predefined Health Checks")
    
    query_options = {
        "Time Series with Missing Parameters": """
        SELECT id, modins, parid, qualifiers, tstype
        FROM ts_sets
        WHERE parid = '' OR parid IS NULL
        ORDER BY modins
        """,
        
        "Time Series with Missing Qualifiers": """
        SELECT id, modins, parid, qualifiers, tstype
        FROM ts_sets
        WHERE qualifiers = '' OR qualifiers IS NULL
        ORDER BY modins
        """,
        
        "Unused Workflows": """
        SELECT cs.id, cs.wf_id, cs.desc
        FROM call_stacks cs
        LEFT JOIN call_stacks child ON child.parent_id = cs.id
        WHERE child.id IS NULL AND cs.parent_id IS NULL
        ORDER BY cs.wf_id
        """,
        
        "Workflows with Most Transformations": """
        SELECT cs.id, cs.wf_id, cs.desc, COUNT(t.id) as transformation_count
        FROM call_stacks cs
        JOIN modins_calls mc ON cs.id = mc.call_stack_id
        JOIN trafos t ON mc.id = t.mic_id
        GROUP BY cs.id
        ORDER BY transformation_count DESC
        LIMIT 20
        """,
        
        "Orphaned Time Series": """
        SELECT ts.id, ts.modins, ts.parid, ts.qualifiers, ts.tstype
        FROM ts_sets ts
        LEFT JOIN links l ON ts.id = l.tss_id
        WHERE l.tss_id IS NULL
        ORDER BY ts.modins, ts.parid
        """
    }
    
    selected_query = st.selectbox("Select a predefined query", options=list(query_options.keys()))
    
    if st.button("Run Predefined Query", key="run_predefined"):
        with st.spinner("Running query..."):
            try:
                query = query_options[selected_query]
                results = run_async_function(
                    st.session_state.tools_interface.execute_custom_query,
                    query=query
                )
                
                if results and results.results:
                    # Convert results to DataFrame
                    df = pd.DataFrame(results.results)
                    
                    # Display as table
                    st.subheader(f"Results: {selected_query}")
                    st.dataframe(df, use_container_width=True)
                    
                    # Show count
                    st.info(f"Found {len(df)} records")
                    
                    # Display markdown content if available
                    if hasattr(results, 'markdown_content') and results.markdown_content:
                        with st.expander("Detailed Results", expanded=False):
                            st.markdown(results.markdown_content)
                    
                    # Add download option
                    csv = df.to_csv(index=False)
                    st.download_button(
                        label="Download Results CSV",
                        data=csv,
                        file_name=f"{selected_query.lower().replace(' ', '_')}.csv",
                        mime="text/csv"
                    )
                else:
                    st.info("No results returned for this query.")
            except Exception as e:
                st.error(f"Error executing query: {str(e)}")
    
    # Custom query input
    st.subheader("Custom SQL Query")
    
    query = st.text_area(
        "Enter SQL Query",
        height=150,
        value="""
-- Example query: Find time series with specific parameter
SELECT id, modins, parid, qualifiers, tstype
FROM ts_sets
WHERE parid LIKE '%H.m%'
LIMIT 20
""",
        help="Enter a SQL query to analyze your FEWS configuration"
    )
    
    if st.button("Run Custom Query", key="run_custom"):
        if query:
            with st.spinner("Running custom query..."):
                try:
                    # Execute the custom query
                    results = run_async_function(
                        st.session_state.tools_interface.execute_custom_query,
                        query=query
                    )
                    
                    if results and results.results:
                        # Convert results to DataFrame
                        df = pd.DataFrame(results.results)
                        
                        # Display as table
                        st.subheader("Custom Query Results")
                        st.dataframe(df, use_container_width=True)
                        
                        # Show count
                        st.info(f"Found {len(df)} records")
                        
                        # Display markdown content if available
                        if hasattr(results, 'markdown_content') and results.markdown_content:
                            with st.expander("Detailed Results", expanded=False):
                                st.markdown(results.markdown_content)
                        
                        # Add download option
                        csv = df.to_csv(index=False)
                        st.download_button(
                            label="Download Results CSV",
                            data=csv,
                            file_name="custom_query_results.csv",
                            mime="text/csv"
                        )
                    else:
                        st.info("No results returned for this query.")
                except Exception as e:
                    st.error(f"Error executing query: {str(e)}")
        else:
            st.warning("Please enter a SQL query.")

